# ------------------------------------------------------------------ path model
@dataclass
class Ring:
    """One closed subpath in absolute coordinates: start point + ("L", p) / ("A", rx, ry, rot, large,
    sweep, p) segments."""
    start: tuple
    segs: list

    def points(self):
        return [self.start] + [s[-1] for s in self.segs]

    def is_polygon(self):
        return all(s[0] == "L" for s in self.segs)


@dataclass
class Shape:
    rings: list
    fill: str                    # "#RRGGBB" | "currentColor" | "url(#id)"
    opacity: float | None
    layer: str                   # brand layer (<g id>) it came from
    src: object = None           # shapely geometry of the brand shape(s) it replaces
    clip: object = None          # region the edge check is limited to (grid only)


@dataclass
class Grad:
    kind: str                    # "l" (x1 y1 x2 y2) | "r" (cx cy r), user space
    coords: list
    stops: list                  # [(offset, colour, opacity | None)]


@dataclass
class Art:
    """One optimised drawing, shared by the SVG file, the React and the web component."""
    w: int                       # viewBox size in 0.01 units
    h: int
    grads: list                  # [Grad] with quantised coords, in order of first use
    paths: list                  # [(d, fill colour | gradient index, opacity | None)]
    edge: float = 0.0            # largest edge displacement measured against brand.py


_TOK = re.compile(r"[A-Za-z]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def parse_path(d):
    """SVG path data (M L H V A Z, absolute or relative, compact numbers) -> [Ring]."""
    toks = _TOK.findall(d)
    rings, i, cmd = [], 0, None
    cur = start = (0.0, 0.0)

    def nums(n):
        nonlocal i
        vals = [float(t) for t in toks[i:i + n]]
        if len(vals) != n or any(t.isalpha() for t in toks[i:i + n]):
            raise ValueError(f"bad path data near token {i}: {d[:60]}")
        i += n
        return vals

    while i < len(toks):
        if toks[i].isalpha():
            cmd = toks[i]
            i += 1
            if cmd in "Zz":
                cur = start
                continue
        elif cmd is None or cmd in "Zz":
            raise ValueError("path data must start with a command")
        rel, C = cmd.islower(), cmd.upper()
        ox, oy = cur if rel else (0.0, 0.0)
        if C == "M":
            x, y = nums(2)
            cur = start = (ox + x, oy + y)
            rings.append(Ring(cur, []))
            cmd = "l" if rel else "L"                     # implicit lineto after moveto
        elif C == "L":
            x, y = nums(2)
            cur = (ox + x, oy + y)
            rings[-1].segs.append(("L", cur))
        elif C == "H":
            cur = ((ox if rel else 0.0) + nums(1)[0], cur[1])
            rings[-1].segs.append(("L", cur))
        elif C == "V":
            cur = (cur[0], (oy if rel else 0.0) + nums(1)[0])
            rings[-1].segs.append(("L", cur))
        elif C == "A":
            rx, ry, rot, la, sw, x, y = nums(7)
            cur = (ox + x, oy + y)
            rings[-1].segs.append(("A", rx, ry, rot, int(la), int(sw), cur))
        else:
            raise ValueError(f"unsupported path command {cmd!r}")
    return rings


# ------------------------------------------------------------------ geometry for the checks
def _arc_points(p0, rx, ry, rot, large, sweep, p1):
    """Flatten an SVG arc (implementation notes F.6.5/F.6.6) to points after p0, ending at p1."""
    if p0 == p1:
        return []
    if rx == 0 or ry == 0:
        return [p1]
    phi = math.radians(rot)
    c, s = math.cos(phi), math.sin(phi)
    dx, dy = (p0[0] - p1[0]) / 2, (p0[1] - p1[1]) / 2
    x1, y1 = c * dx + s * dy, -s * dx + c * dy
    rx, ry = abs(rx), abs(ry)
    lam = x1 ** 2 / rx ** 2 + y1 ** 2 / ry ** 2
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = rx ** 2 * ry ** 2 - rx ** 2 * y1 ** 2 - ry ** 2 * x1 ** 2
    den = rx ** 2 * y1 ** 2 + ry ** 2 * x1 ** 2
    co = math.sqrt(max(0.0, num / den)) * (-1 if large == sweep else 1)
    cxp, cyp = co * rx * y1 / ry, -co * ry * x1 / rx
    cx = c * cxp - s * cyp + (p0[0] + p1[0]) / 2
    cy = s * cxp + c * cyp + (p0[1] + p1[1]) / 2

    def ang(u, v):
        return math.atan2(u[0] * v[1] - u[1] * v[0], u[0] * v[0] + u[1] * v[1])

    u = ((x1 - cxp) / rx, (y1 - cyp) / ry)
    t1 = ang((1, 0), u)
    dt = ang(u, ((-x1 - cxp) / rx, (-y1 - cyp) / ry))
    if not sweep and dt > 0:
        dt -= 2 * math.pi
    elif sweep and dt < 0:
        dt += 2 * math.pi
    step = 2 * math.acos(max(-1.0, 1 - ARC_SAG / max(rx, ry)))
    n = max(2, math.ceil(abs(dt) / step))
    pts = []
    for j in range(1, n):
        t = t1 + dt * j / n
        pts.append((cx + rx * math.cos(t) * c - ry * math.sin(t) * s, cy + rx * math.cos(t) * s + ry * math.sin(t) * c))
    return pts + [p1]


def _flat(ring):
    pts = [ring.start]
    for sg in ring.segs:
        pts += [sg[1]] if sg[0] == "L" else _arc_points(pts[-1], *sg[1:6], sg[6])
    if len(pts) > 1 and pts[-1] == pts[0]:
        pts.pop()
    return pts


def _signed_area(pts):
    return 0.5 * sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]))


def geometry(rings):
    """Filled region of a path under the nonzero rule (SVG's default), as a shapely geometry."""
    rs = [p for p in (_flat(r) for r in rings) if len(p) >= 3 and abs(_signed_area(p)) > 1e-9]
    if not rs:
        return Polygon()
    if len(rs) == 1:
        return Polygon(rs[0]).buffer(0)
    polys = [Polygon(p) for p in rs]
    sign = np.array([1 if _signed_area(p) > 0 else -1 for p in rs])
    faces = list(polygonize(unary_union([LineString(p + p[:1]) for p in rs])))
    probes = [f.representative_point() for f in faces]
    hit_face, hit_ring = STRtree(polys).query(probes, predicate="within")
    winding = np.bincount(hit_face, weights=sign[hit_ring], minlength=len(faces))
    return unary_union([f for f, w in zip(faces, winding) if w != 0])


def _segments(g):
    parts = shapely.get_parts(shapely.boundary(g))
    segs = []
    for ls in parts:
        c = shapely.get_coordinates(ls)
        if len(c) > 1:
            segs.append(np.stack([c[:-1], c[1:]], axis=1))
    return shapely.linestrings(np.concatenate(segs))


def _directed(a, b, step):
    pts = shapely.points(shapely.get_coordinates(shapely.segmentize(shapely.boundary(a), step)))
    _, dist = STRtree(_segments(b)).query_nearest(pts, return_distance=True)
    return float(dist.max())


def edge_distance(a, b):
    """Symmetric Hausdorff distance between the outlines of two regions (design units)."""
    if a.is_empty or b.is_empty:
        return 0.0 if a.is_empty and b.is_empty else math.inf
    step = max(0.25, (a.boundary.length + b.boundary.length) / 400000)
    return max(_directed(a, b, step), _directed(b, a, step))


# ------------------------------------------------------------------ reading brand documents
_PAINT = {"fill", "fill-opacity", "id", "data-name"}


def read_doc(svg):
    """Brand SVG document -> (viewBox, {id: Grad}, [Shape]). Anything unexpected raises, so a new
    construct in brand.py is noticed here instead of being dropped silently."""
    root = ET.fromstring(svg)
    vb = tuple(float(v) for v in root.get("viewBox").split())
    grads, shapes = {}, []

    def check(el, allowed):
        extra = set(el.attrib) - allowed
        if extra:
            raise ValueError(f"<{el.tag}> has unsupported attributes {sorted(extra)}")

    def walk(el, layer):
        tag = el.tag.split("}")[-1]
        if tag in ("svg", "defs", "g"):
            if tag == "g":
                check(el, {"id", "data-name"})               # no transforms: none of our variants use one
                layer = el.get("id", layer)
            for ch in el:
                walk(ch, layer)
        elif tag == "title":
            pass
        elif tag in ("linearGradient", "radialGradient"):
            keys = ("x1", "y1", "x2", "y2") if tag == "linearGradient" else ("cx", "cy", "r")
            check(el, set(keys) | {"id", "gradientUnits"})
            if el.get("gradientUnits") != "userSpaceOnUse":
                raise ValueError("only userSpaceOnUse gradients are supported")
            stops = []
            for st in el:
                check(st, {"offset", "stop-color", "stop-opacity"})
                op = st.get("stop-opacity")
                stops.append((float(st.get("offset", 0)), st.get("stop-color"), None if op is None else float(op)))
            grads[el.get("id")] = Grad(tag[0], [float(el.get(a, 0)) for a in keys], stops)
        elif tag == "path":
            check(el, _PAINT | {"d"})
            shapes.append(_shape(el, _true_half_circles(parse_path(el.get("d"))), layer))
        elif tag == "circle":
            check(el, _PAINT | {"cx", "cy", "r"})
            cx, cy, r = (float(el.get(a)) for a in ("cx", "cy", "r"))
            shapes.append(_shape(el, [_circle_ring(cx, cy, r, 1)], layer))
        elif tag == "rect":
            check(el, _PAINT | {"x", "y", "width", "height"})
            x, y, w, h = (float(el.get(a, 0)) for a in ("x", "y", "width", "height"))
            shapes.append(_shape(el, [Ring((x, y), [("L", (x + w, y)), ("L", (x + w, y + h)), ("L", (x, y + h))])], layer))
        else:
            raise ValueError(f"unsupported element <{tag}>")

    walk(root, "")
    return vb, grads, shapes


def _shape(el, rings, layer):
    op = el.get("fill-opacity")
    sh = Shape(rings, el.get("fill"), None if op is None or float(op) >= 1 else float(op), layer)
    sh.src = geometry(rings)
    return sh


def _true_half_circles(rings):
    """brand.fmt rounds a half arc's radius and endpoints separately, so its circles (the tech
    node, the ambient light) can come out with r up to 0.0005 above half the chord; renderers then
    move each half's centre off the chord by sqrt(r^2 - (c/2)^2), up to 0.2 units. brand.py
    constructs true circles, so half arcs are read with r = chord / 2."""
    for r in rings:
        prev = r.start
        for j, sg in enumerate(r.segs):
            if sg[0] == "A" and sg[1] == sg[2] and abs(2 * sg[1] - math.dist(prev, sg[-1])) <= 1e-3 * sg[1]:
                half = math.dist(prev, sg[-1]) / 2
                r.segs[j] = ("A", half, half) + sg[3:]
            prev = sg[-1]
    return rings


def _circle_ring(cx, cy, r, sweep):
    """Circle as two half arcs; sweep 1 runs clockwise on screen (positive area in y-down)."""
    return Ring((cx - r, cy), [("A", r, r, 0, 1, sweep, (cx + r, cy)), ("A", r, r, 0, 1, sweep, (cx - r, cy))])


# ------------------------------------------------------------------ rewrites (all verified later)
def _translate(shapes, grads, dx, dy):
    def mv(p):
        return (p[0] + dx, p[1] + dy)

    for sh in shapes:
        sh.rings = [Ring(mv(r.start), [sg[:-1] + (mv(sg[-1]),) for sg in r.segs]) for r in sh.rings]
        sh.src = shapely.transform(sh.src, lambda c: c + np.array([dx, dy]))
    for g in grads.values():
        n = 4 if g.kind == "l" else 2
        g.coords = [v + (dx if j % 2 == 0 else dy) if j < n else v for j, v in enumerate(g.coords)]


def _merge_flat(shapes):
    """Merge runs of opaque shapes of one solid colour into one path (painting them separately
    looks the same, except for the anti-aliased seams this removes)."""
    out = []
    for sh in shapes:
        prev = out[-1] if out else None
        if (prev and sh.opacity is None and prev.opacity is None and sh.fill == prev.fill
                and not sh.fill.startswith("url(") and sh.layer == prev.layer):
            prev.src = unary_union([prev.src, sh.src])
            prev.rings = None                               # rebuilt from the union below
        else:
            out.append(sh)
    for sh in out:
        if sh.rings is None:
            sh.rings = []
            for p in shapely.get_parts(sh.src):
                p = orient(p, 1.0)
                for ring in [p.exterior, *p.interiors]:
                    pts = [tuple(c) for c in ring.coords][:-1]
                    sh.rings.append(Ring(pts[0], [("L", q) for q in pts[1:]]))
    return out


def _as_circle(ring):
    """A polygonised circle (>= 24 vertices on one radius) -> two arcs with the same winding."""
    if not ring.is_polygon() or len(ring.segs) < 23:
        return ring
    pts = np.array(_flat(ring))
    c = pts.mean(axis=0)
    rad = np.hypot(*(pts - c).T)
    if rad.max() - rad.min() > 0.004:
        return ring
    return _circle_ring(float(c[0]), float(c[1]), float(rad.mean()), 1 if _signed_area(_flat(ring)) > 0 else 0)


def _as_strips(sh, grad, width, height):
    """The tech icon's construction grid is a union of axis-aligned hairline strips intersected
    with a circle whose radius is the grid gradient's radius. That gradient is fully transparent at
    the circle, so the strips alone draw the same picture. Returns the replacement or None."""
    if grad is None or grad.kind != "r" or grad.stops[-1][2] != 0 or grad.stops[-1][0] != 1:
        return None
    xs, ys = set(), set()
    for r in sh.rings:
        if not r.is_polygon():
            return None
        pts = r.points()
        for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
            if x0 == x1 and abs(y1 - y0) > 2:
                xs.add(x0)
            elif y0 == y1 and abs(x1 - x0) > 2:
                ys.add(y0)

    def pairs(vals):
        v = sorted(vals)
        if len(v) < 2 or len(v) % 2:
            return None
        w = v[1] - v[0]
        if any(abs((v[j + 1] - v[j]) - w) > 2e-3 for j in range(0, len(v), 2)):
            return None
        return [(v[j], v[j + 1]) for j in range(0, len(v), 2)]

    vx, hy = pairs(xs), pairs(ys)
    if not vx or not hy:
        return None
    # full-height / full-width rectangles, all wound the same way, so overlaps stay filled once
    rings = [Ring((a, 0.0), [("L", (b, 0.0)), ("L", (b, height)), ("L", (a, height))]) for a, b in vx]
    rings += [Ring((0.0, a), [("L", (width, a)), ("L", (width, b)), ("L", (0.0, b))]) for a, b in hy]
    strips = geometry(rings)
    # detection check: the exact strips, clipped like brand.py does, must give back the brand grid.
    # It ignores the outermost unit, where the gradient is below 0.1% opacity and brand.py clips
    # with its own polygonal circle.
    cx, cy, rad = grad.coords
    clip = Point(cx, cy).buffer(rad - 1.0, resolution=256)
    if edge_distance(strips.intersection(clip), sh.src.intersection(clip)) > 0.01:
        return None
    # the quantisation check (in build_art) then compares against the exact strips, unclipped
    return Shape(rings, sh.fill, sh.opacity, sh.layer, src=strips)


# ------------------------------------------------------------------ quantising and encoding
def q(v):
    """Coordinate -> integer hundredths, coarsened to 0.1 or 1 unit where the error stays within
    AXIS_TOL."""
    for step in (100, 10):
        r = round(v * 100 / step) * step
        if abs(r / 100 - v) <= AXIS_TOL:
            return r
    return round(v * 100)


def num(v):
    """Integer hundredths -> shortest decimal text: 0, .5, -.25, 480.9."""
    neg, a = v < 0, abs(v)
    s = str(a // 100) + (f".{a % 100:02d}".rstrip("0") if a % 100 else "")
    if s.startswith("0."):
        s = s[1:]
    return ("-" if neg else "") + s


def dec(x, nd=3):
    """Offsets and opacities: up to nd decimals, no leading zero."""
    s = f"{x:.{nd}f}".rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s.replace("0.", ".", 1) if s.startswith("0.") else s


def short_hex(c):
    """#AABBCC -> #ABC when that is the same colour; other values pass through."""
    if re.fullmatch(r"#[0-9A-Fa-f]{6}", c) and c[1] == c[2] and c[3] == c[4] and c[5] == c[6]:
        return "#" + c[1] + c[3] + c[5]
    return c


def _qring(ring):
    """Quantise one ring; drop duplicate and collinear vertices; None if nothing is left."""
    def qp(p):
        return (q(p[0]), q(p[1]))

    if ring.is_polygon():
        pts = []
        for p in map(qp, ring.points()):
            if not pts or p != pts[-1]:
                pts.append(p)
        while len(pts) > 1 and pts[-1] == pts[0]:
            pts.pop()
        changed = True
        while changed and len(pts) >= 3:
            changed = False
            for j in range(len(pts)):
                a, b, c = pts[j - 1], pts[j], pts[(j + 1) % len(pts)]
                if (b[0] - a[0]) * (c[1] - b[1]) - (b[1] - a[1]) * (c[0] - b[0]) == 0:
                    del pts[j]
                    changed = True
                    break
        if len(pts) < 3:
            return None
        return Ring(pts[0], [("L", p) for p in pts[1:]])
    segs, cur, orig = [], qp(ring.start), ring.start
    for sg in ring.segs:
        end = qp(sg[-1])
        if sg[0] == "L":
            if end != cur:
                segs.append(("L", end))
        else:
            _, rx, ry, rot, la, sw, _p = sg
            if abs(2 * rx - math.dist(orig, sg[-1])) <= 1e-3 * rx:
                # half circle: a radius above half the (quantised) chord would move the centre off
                # the chord by sqrt(r^2 - (c/2)^2); at or below it the renderer centres it exactly
                rr = math.floor(math.dist(cur, end) / 2)
            else:
                rr = round(rx * 100)
            segs.append(("A", rr, rr, rot, la, sw, end))
        cur, orig = end, sg[-1]
    return Ring(qp(ring.start), segs)


class _Path:
    """Shortest path data: picks absolute/relative/H/V per segment, omits repeated command
    letters and every separator the grammar allows (a minus sign, or a dot after a decimal)."""

    def __init__(self):
        self.out, self.cmd, self.last = [], None, None

    def _cost(self, cmd, vals):
        return len(self._text(cmd, vals))

    def _text(self, cmd, vals):
        s, last = ("" if cmd == self.cmd else cmd), (None if cmd != self.cmd else self.last)
        for v in vals:
            if last is not None and not (v[0] == "-" or (v[0] == "." and "." in last)):
                s += " "
            s += v
            last = v
        return s

    def emit(self, options):
        cmd, vals = min(options, key=lambda o: self._cost(*o))
        self.out.append(self._text(cmd, vals))
        self.cmd, self.last = cmd, vals[-1] if vals else None
        if cmd in "Mm":                                     # a moveto implies lineto for more pairs
            self.cmd = "L" if cmd == "M" else "l"

    def close(self):
        self.out.append("z")
        self.cmd = self.last = None

    def text(self):
        return "".join(self.out)


def encode(rings):
    p, cur = _Path(), (0, 0)
    for r in rings:
        s = r.start
        p.emit([("M", [num(s[0]), num(s[1])]), ("m", [num(s[0] - cur[0]), num(s[1] - cur[1])])])
        cur = s
        segs = r.segs[:-1] if r.segs and r.segs[-1][0] == "L" and r.segs[-1][1] == s else r.segs
        for sg in segs:
            x, y = sg[-1]
            if sg[0] == "L":
                if y == cur[1]:
                    opts = [("H", [num(x)]), ("h", [num(x - cur[0])])]
                elif x == cur[0]:
                    opts = [("V", [num(y)]), ("v", [num(y - cur[1])])]
                else:
                    opts = [("L", [num(x), num(y)]), ("l", [num(x - cur[0]), num(y - cur[1])])]
            else:
                _, rx, ry, rot, la, sw, _p = sg
                head = [num(rx), num(ry), dec(rot), str(la), str(sw)]
                opts = [("A", head + [num(x), num(y)]), ("a", head + [num(x - cur[0]), num(y - cur[1])])]
            p.emit(opts)
            cur = (x, y)
        p.close()
        cur = s
    return p.text()


# ------------------------------------------------------------------ build one drawing
def build_art(v: Variant, k):
    vb, grads, shapes = read_doc(v.doc(k))
    if v.tight:
        _translate(shapes, grads, -vb[0], -vb[1])
    for sh in shapes:
        sh.fill = v.recolour.get(sh.fill, sh.fill)
    shapes = _merge_flat(shapes)
    final = []
    for sh in shapes:
        if sh.layer == "grid":
            gid = sh.fill[5:-1] if sh.fill.startswith("url(#") else None
            strips = _as_strips(sh, grads.get(gid), vb[2], vb[3])
            if strips is not None:
                final.append(strips)
                continue
        sh.rings = [_as_circle(r) for r in sh.rings]
        final.append(sh)

    order, paths, worst = [], [], 0.0
    xmax = ymax = 0
    for sh in final:
        rings = [r for r in map(_qring, sh.rings) if r is not None]
        d = encode(rings)
        # the check: parse what we wrote and compare it with the brand shape
        got = geometry(parse_path(d))
        if sh.clip is not None:
            got = got.intersection(sh.clip)
        err = edge_distance(sh.src, got)
        if err > MAX_EDGE:
            raise AssertionError(f"{v.file}: layer {sh.layer!r} moved {err:.4f} units (> {MAX_EDGE})")
        worst = max(worst, err)
        for r in rings:
            for x, y in r.points():
                xmax, ymax = max(xmax, x), max(ymax, y)
        if sh.fill.startswith("url(#"):
            gid = sh.fill[5:-1]
            if gid not in order:
                order.append(gid)
            fill = order.index(gid)
        else:
            fill = short_hex(sh.fill)
        paths.append((d, fill, sh.opacity))
    if v.tight:                                               # hug the quantised artwork (the marks
        w, h = xmax, ymax                                     # have no arcs: vertices bound them)
    else:
        w, h = q(vb[2]), q(vb[3])
    qgrads = []
    for gid in order:
        g = grads[gid]
        n = 4 if g.kind == "l" else 3
        qgrads.append(Grad(g.kind, [q(c) for c in g.coords[:n]], [(o, short_hex(c), a) for o, c, a in g.stops]))
    return Art(w, h, qgrads, paths, worst)


# ------------------------------------------------------------------ emit: standalone SVG
def _grad_xml(g: Grad, gid):
    if g.kind == "l":
        x1, y1, x2, y2 = g.coords
        # x1 / y1 default to 0 (0% of the viewport in user space)
        attrs = "".join(f' {n}="{num(c)}"' for n, c in (("x1", x1), ("y1", y1)) if c) + f' x2="{num(x2)}" y2="{num(y2)}"'
        tag = "linearGradient"
    else:
        attrs = "".join(f' {n}="{num(c)}"' for n, c in zip(("cx", "cy", "r"), g.coords))
        tag = "radialGradient"
    stops = ""
    for o, c, a in g.stops:                                  # offset defaults to 0
        stops += ("<stop" + (f' offset="{dec(o)}"' if o else "") + f' stop-color="{c}"'
                  + (f' stop-opacity="{dec(a)}"' if a is not None else "") + "/>")
    return f'<{tag} id="{gid}"{attrs} gradientUnits="userSpaceOnUse">{stops}</{tag}>'


def _gid(i):
    return chr(ord("a") + i)


def svg_file(art: Art, title=TITLE):
    defs = "".join(_grad_xml(g, _gid(i)) for i, g in enumerate(art.grads))
    body = ""
    for d, fill, op in art.paths:
        f = f"url(#{_gid(fill)})" if isinstance(fill, int) else fill
        body += f'<path fill="{f}"' + (f' fill-opacity="{dec(op)}"' if op is not None else "") + f' d="{d}"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {num(art.w)} {num(art.h)}" role="img">'
            f"<title>{title}</title>" + (f"<defs>{defs}</defs>" if defs else "") + body + "</svg>\n")


# ------------------------------------------------------------------ emit: component data
def _js_art(art: Art, indent="  "):
    """Art as a JS/TS object literal: { w, h, g: [[kind, coords, stops]], p: [[d, fill, opacity?]] }."""
    def stop(o, c, a):
        return f"[{dec(o)}, '{c}'" + (f", {dec(a)}" if a is not None else "") + "]"

    g = ",\n".join(f"{indent}    ['{x.kind}', [{', '.join(num(c) for c in x.coords)}], [{', '.join(stop(*s) for s in x.stops)}]]"
                   for x in art.grads)
    p = ",\n".join(f"{indent}    ['{d}', " + (str(f) if isinstance(f, int) else f"'{f}'") +
                   (f", {dec(op)}" if op is not None else "") + "]" for d, f, op in art.paths)
    return (f"{{\n{indent}  w: {num(art.w)},\n{indent}  h: {num(art.h)},\n"
            f"{indent}  g: [" + (f"\n{g},\n{indent}  " if g else "") + "],\n"
            f"{indent}  p: [\n{p},\n{indent}  ],\n{indent}}}")


def _js_table(arts):
    return "{\n" + "".join(f"  '{key}': {_js_art(a)},\n" for key, a in arts.items()) + "}"


