"""Developer kit: production SVGs, a React component, a web component and design tokens.

    python3 brand/tools/build_web.py         # regenerates every file in brand/web/

Everything in brand/web/ is derived from brand.py at build time and nothing there is edited by
hand: the artwork comes from the brand documents (doc_mark / doc_badge / doc_tech, with the
raster-safe trapped facets wherever the browser rasterises), the colours from PALETTE /
PALETTE_OKLCH / NEUTRAL and the geometry tokens from master(). A change to the master is one edit
in brand.py plus one re-run of this file.

How the production SVGs are optimised. The design is never touched: no facet is recoloured,
rotated, stretched, outlined or moved, and every corner stays sharp.
  * ids, data-names, groups, xlink and editor titles go; one role="img" + <title> remains.
  * Marks get a tight viewBox: the artwork is translated so the box starts at 0 0 and hugs the K.
  * Coordinates are quantised to 0.01 units, and to 0.1 or 1 unit where that moves the value no
    more than AXIS_TOL on either axis (so no vertex moves more than 0.043 units).
  * Duplicate and collinear vertices go; polygonised circles (the trace pads) become two arcs;
    the tech icon's construction grid - hairline strips clipped by a circle - becomes the plain
    strips, because its radial gradient is already fully transparent at that circle.
  * Opaque shapes of one colour (the one-colour marks) are merged into one path: no inner seams.
  * Path data uses the shortest of absolute / relative / H / V commands with minimal separators.
Every output path is parsed back and compared with the brand shape it came from; the build fails
if any edge moved more than MAX_EDGE units.

The React component and the web component embed the same optimised data (no geometry at
runtime) and give each instance its own gradient ids.
"""
